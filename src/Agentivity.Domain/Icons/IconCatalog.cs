using System.Reflection;
using System.Text.Json;
using Agentivity.Domain.Workflow;

namespace Agentivity.Domain.Icons;

/// <summary>One icon a user can choose: a reference into an icon set (<see cref="Type"/> + <see cref="Value"/>) and the name search finds it by.</summary>
/// <param name="Type">The icon set — <see cref="NodeIconDef.MaterialType"/> today.</param>
/// <param name="Value">The icon inside the set. For Material, its code point in uppercase hex (<c>E322</c>) — the one thing that is stored.</param>
/// <param name="Name">The Material name (<c>hotel_baseline</c>). For search and tooltips only; never stored.</param>
public sealed record IconInfo(string Type, string Value, string Name)
{
    /// <summary>The reference to store on whatever the icon is chosen for.</summary>
    public NodeIconDef ToRef() => new() { Type = Type, Value = Value };
}

/// <summary>
/// The catalog of icons a user can choose from, organised by icon set (<see cref="NodeIconDef.Type"/>) so any screen with an
/// icon picker can use it. The standard set is Material Icons — the font Flutter bundles — identified by code point, so an
/// icon is the same glyph in Studio and in every SDK. Generated by <c>tools/generate-icons.mjs</c>.
/// </summary>
public static class IconCatalog
{
    private static readonly JsonSerializerOptions ReadOptions = new() { PropertyNameCaseInsensitive = true };

    /// <summary>The icon sets this catalog offers.</summary>
    public static IReadOnlyList<string> Types { get; } = [NodeIconDef.MaterialType];

    /// <summary>Every icon, sorted by name.</summary>
    public static IReadOnlyList<IconInfo> All { get; } = Load();

    private static readonly HashSet<string> Known = All.Select(i => Key(i.Type, i.Value)).ToHashSet(StringComparer.Ordinal);

    /// <summary>True when <paramref name="value"/> (a hex code point, any case) is an icon of the <paramref name="type"/> set.</summary>
    public static bool Contains(string? type, string? value) => type is not null && value is not null && Known.Contains(Key(type.Trim(), value.Trim()));

    /// <summary>The icons of a set (all sets when <paramref name="type"/> is null), optionally only those whose name contains <paramref name="query"/>.</summary>
    public static IEnumerable<IconInfo> Find(string? type = null, string? query = null)
    {
        IEnumerable<IconInfo> icons = All;
        if (!string.IsNullOrWhiteSpace(type))
            icons = icons.Where(i => string.Equals(i.Type, type.Trim(), StringComparison.OrdinalIgnoreCase));

        var q = query?.Trim().Replace(' ', '_');
        if (!string.IsNullOrEmpty(q))
            icons = icons.Where(i => i.Name.Contains(q, StringComparison.OrdinalIgnoreCase));
        return icons;
    }

    private static string Key(string type, string value) => $"{type.ToLowerInvariant()}:{value.ToUpperInvariant()}";

    private static IReadOnlyList<IconInfo> Load()
    {
        using var stream =
            typeof(IconCatalog).Assembly.GetManifestResourceStream("Agentivity.Domain.Icons.material-icons.json")
            ?? throw new InvalidOperationException("The material-icons.json resource is missing from Agentivity.Domain.");
        var entries = JsonSerializer.Deserialize<List<Entry>>(stream, ReadOptions) ?? [];
        return entries.Select(e => new IconInfo(NodeIconDef.MaterialType, e.C.ToUpperInvariant(), e.N)).ToList();
    }

    private sealed record Entry(string C, string N);
}
