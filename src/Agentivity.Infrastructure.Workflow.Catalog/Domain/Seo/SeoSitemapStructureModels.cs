namespace Agentivity.Infrastructure.Workflow.Catalog.Seo;

/// <summary>
/// Represents a page from a sitemap
/// </summary>
public sealed class SitemapPage
{
    public string Url { get; set; } = string.Empty;
    public string? Title { get; set; }
    public DateTime? LastModified { get; set; }
    public string? ChangeFrequency { get; set; }
    public decimal? Priority { get; set; }
    public Dictionary<string, string>? Metadata { get; set; }

    // Enriched data from scraping
    public string? MetaDescription { get; set; }
    public string? H1 { get; set; }
    public string? Excerpt { get; set; }
    public List<string>? InternalLinks { get; set; }
    public List<string>? ExternalLinks { get; set; }

    /// <summary>
    /// Whether the page is indexable (no noindex meta tag).
    /// Default true because pages in sitemap should be indexable.
    /// Set to false if meta robots contains "noindex".
    /// </summary>
    public bool IsIndexable { get; set; } = true;

    /// <summary>
    /// Raw meta robots content (e.g., "index, follow" or "noindex, nofollow")
    /// </summary>
    public string? MetaRobots { get; set; }

    // Link metrics
    public int InternalLinkCount => InternalLinks?.Count ?? 0; // Outbound links
    public int ExternalLinkCount => ExternalLinks?.Count ?? 0;
    public int InboundLinkCount { get; set; } // Links TO this page (from internal pages)

    // Pillar detection scores (0-100 each)
    public double PageRankScore { get; set; } // Internal authority via PageRank
    public double InboundLinksScore { get; set; } // Normalized inbound link count
    public double OutboundLinksScore { get; set; } // Normalized outbound link count
    public double StructureScore { get; set; } // Has H1, TOC, proper metadata
    public double DepthScore { get; set; } // URL proximity to homepage (lower depth = higher score)
    public double SemanticBreadthScore { get; set; } // Topic diversity (requires embeddings)

    // URL structure
    public int UrlDepth { get; set; } // Number of path segments

    // Final pillar score (weighted combination of all heuristics, 0-100)
    public double PillarScore { get; set; }

    // Is this page a pillar candidate?
    public bool IsPillarCandidate { get; set; }
}

/// <summary>
/// Represents a content pillar: a high-authority page that can contain sub-pillars and/or leaf pages
/// RECURSIVE structure to support multi-level hierarchies (e.g., /academy/ → /academy/technical-indicators/ → pages)
/// </summary>
public sealed class ContentPillar
{
    /// <summary>
    /// The central pillar page with high PageRank and strong internal linking
    /// This is a REAL page with high authority (e.g., /academy/seo-guide)
    /// </summary>
    public SitemapPage PillarPage { get; set; } = new();

    /// <summary>
    /// RECURSIVE: Sub-pillars under this pillar (e.g., /academy/technical-indicators/ under /academy/)
    /// These are pillar pages themselves but at a lower hierarchical level
    /// </summary>
    public List<ContentPillar> SubPillars { get; set; } = [];

    /// <summary>
    /// Leaf pages directly under this pillar (not sub-pillars)
    /// These are regular content pages that link to/from this pillar
    /// </summary>
    public List<SitemapPage> LeafPages { get; set; } = [];

    /// <summary>
    /// Optional SEO-optimized title for this pillar (generated by LLM)
    /// If null, use PillarPage.Title
    /// </summary>
    public string? SeoTitle { get; set; }

    /// <summary>
    /// Optional SEO description for this pillar group (generated by LLM)
    /// </summary>
    public string? SeoDescription { get; set; }

    /// <summary>
    /// Extracted keywords for this pillar content group (generated by LLM)
    /// </summary>
    public List<string> Keywords { get; set; } = [];

    /// <summary>
    /// Hierarchy level (0 = top-level, 1 = sub-pillar, 2 = sub-sub-pillar, etc.)
    /// Useful for UI rendering and understanding structure depth
    /// </summary>
    public int Level { get; set; } = 0;

    /// <summary>
    /// Total count of all descendant pages (recursive: includes sub-pillars' pages)
    /// </summary>
    public int TotalDescendantPages => LeafPages.Count + SubPillars.Sum(sp => sp.TotalDescendantPages);
}

/// <summary>
/// Represents a topic cluster: semantically related pages WITHOUT a central pillar page
/// These are opportunities to create missing pillar content
/// </summary>
public sealed class TopicCluster
{
    /// <summary>
    /// Topic/theme of this cluster (e.g., "Crypto Trading", "Technical Analysis")
    /// </summary>
    public string Topic { get; set; } = string.Empty;

    /// <summary>
    /// Pages grouped by semantic similarity (embeddings/LLM)
    /// No single page has dominant authority - opportunity for pillar creation
    /// </summary>
    public List<SitemapPage> Pages { get; set; } = [];

    /// <summary>
    /// SEO description of this topic cluster
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Keywords extracted from this cluster
    /// </summary>
    public List<string> Keywords { get; set; } = [];
}

/// <summary>
/// Represents the complete site structure (no homepage - it's a special hub)
/// </summary>
public sealed class SiteStructure
{
    public string SiteUrl { get; set; } = string.Empty;
    public DateTime AnalyzedAt { get; set; } = DateTime.UtcNow;
    public int TotalPages { get; set; }

    /// <summary>
    /// Content pillars: high-authority pages with sub-pages
    /// Determined by PageRank + internal link graph
    /// </summary>
    public List<ContentPillar> Pillars { get; set; } = [];

    /// <summary>
    /// Topic clusters: semantic groups WITHOUT a dominant pillar page
    /// Opportunities to create missing pillar content
    /// </summary>
    public List<TopicCluster> TopicClusters { get; set; } = [];

    /// <summary>
    /// Orphan pages: isolated pages with few/no internal links or utility pages
    /// (e.g., /about, /privacy, poorly linked articles)
    /// </summary>
    public List<SitemapPage> OrphanPages { get; set; } = [];
}

/// <summary>
/// Utility class to filter junk URLs (feeds, APIs, assets, etc.) that pollute PageRank
/// </summary>
public static class UrlFilter
{
    private static readonly string[] JunkPatterns =
    [
        // WordPress feeds
        "/feed/",
        "/comments/feed/",
        "/trackback/",
        "/rss/",
        "/atom/",
        // WordPress API & admin
        "/wp-json/",
        "/wp-admin/",
        "/wp-content/",
        "/wp-includes/",
        "xmlrpc.php",
        "wp-login.php",
        // oEmbed endpoints
        "/oembed/",
        "/embed?",
        "format=xml",
        // Assets (CSS, JS, fonts, images)
        ".css",
        ".js",
        ".map",
        ".woff",
        ".woff2",
        ".ttf",
        ".eot",
        ".svg",
        ".png",
        ".jpg",
        ".jpeg",
        ".gif",
        ".webp",
        ".ico",
        ".pdf",
        // External CDNs
        "fonts.googleapis.com",
        "fonts.gstatic.com",
        "googletagmanager.com",
        "google-analytics.com",
        "doubleclick.net",
        "facebook.com/tr",
        "//www.googletagmanager",
        "//fonts.googleapis",
        // Query strings (pagination, share, reply)
        "?share=",
        "?replytocom=",
        "?p=",
        "?page_id=",
        "?attachment_id=",
        "#038;",
        "&#038;",
        // WordPress taxonomy archives (usually not pillar content)
        "/author/",
        "/tag/",
        "/category/",
        "/page/", // Pagination
        "/date/",
        // Common non-content paths
        "/search",
        "/cart",
        "/checkout",
        "/account",
        "/login",
        "/register",
        "/privacy",
        "/terms",
        "/cookies",
        "/sitemap.xml",
        "/robots.txt",
    ];

    /// <summary>
    /// Check if URL is junk (feed, API, asset, pagination, etc.)
    /// </summary>
    public static bool IsJunkUrl(string url)
    {
        if (string.IsNullOrWhiteSpace(url))
            return true;

        string lowerUrl = url.ToLowerInvariant();

        foreach (string pattern in JunkPatterns)
        {
            if (lowerUrl.Contains(pattern))
                return true;
        }

        return false;
    }

    /// <summary>
    /// Filter junk URLs from a list (removes feeds, assets, duplicates)
    /// </summary>
    public static List<string> FilterJunkUrls(List<string>? urls)
    {
        return urls == null || urls.Count == 0 ? [] : urls.Where(u => !IsJunkUrl(u)).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
    }

    /// <summary>
    /// Filter URLs to keep only those from the same domain (excluding self-links and junk)
    /// </summary>
    public static List<string> FilterInternalUrls(List<string>? urls, string siteDomain, string? currentPageUrl = null)
    {
        if (urls == null || urls.Count == 0)
            return [];

        Uri? siteUri;
        try
        {
            siteUri = new Uri(siteDomain);
        }
        catch
        {
            return []; // Invalid site domain
        }

        // Normalize current page URL for comparison
        string? normalizedCurrentUrl = null;
        if (!string.IsNullOrEmpty(currentPageUrl))
        {
            try
            {
                normalizedCurrentUrl = new Uri(currentPageUrl).AbsoluteUri.TrimEnd('/').ToLowerInvariant();
            }
            catch { }
        }

        var filtered = new List<string>();
        int rejectedSelf = 0;
        int rejectedJunk = 0;
        int rejectedExternal = 0;

        foreach (string url in urls)
        {
            if (IsJunkUrl(url))
            {
                rejectedJunk++;
                continue;
            }

            if (!IsSameDomain(url, siteUri))
            {
                rejectedExternal++;
                continue;
            }

            // ✅ FILTER self-links (page linking to itself)
            if (normalizedCurrentUrl != null)
            {
                try
                {
                    string normalizedUrl = new Uri(url).AbsoluteUri.TrimEnd('/').ToLowerInvariant();
                    if (normalizedUrl == normalizedCurrentUrl)
                    {
                        rejectedSelf++;
                        continue; // Exclude self-link
                    }
                }
                catch { }
            }

            filtered.Add(url);
        }

        // Log rejection stats if significant filtering occurred
        if (urls.Count > 0 && filtered.Count == 0)
        {
            Console.WriteLine($"⚠️ ALL {urls.Count} links filtered out! Self: {rejectedSelf}, Junk: {rejectedJunk}, External: {rejectedExternal}");
        }

        return filtered.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
    }

    /// <summary>
    /// Check if URL is from the same domain as the site
    /// </summary>
    private static bool IsSameDomain(string url, Uri siteUri)
    {
        try
        {
            var uri = new Uri(url);
            return uri.Host.Equals(siteUri.Host, StringComparison.OrdinalIgnoreCase);
        }
        catch
        {
            return false; // Invalid URL = external
        }
    }
}

/// <summary>
/// Represents a suggested internal link
/// </summary>
public sealed class InternalLinkSuggestion
{
    [System.Text.Json.Serialization.JsonPropertyName("target_url")]
    public string TargetUrl { get; set; } = string.Empty;

    [System.Text.Json.Serialization.JsonPropertyName("target_title")]
    public string TargetTitle { get; set; } = string.Empty;

    [System.Text.Json.Serialization.JsonPropertyName("suggested_anchor_text")]
    public string SuggestedAnchorText { get; set; } = string.Empty;

    [System.Text.Json.Serialization.JsonPropertyName("relevance")]
    public string Relevance { get; set; } = string.Empty; // "high", "medium", "low"

    [System.Text.Json.Serialization.JsonPropertyName("reason")]
    public string? Reason { get; set; }

    [System.Text.Json.Serialization.JsonPropertyName("context_suggestion")]
    public string? ContextSuggestion { get; set; }

    /// <summary>SEO category (parent, sibling, children, ancestor, cross-pillar)</summary>
    public string? Category { get; set; }

    /// <summary>Weight of the category (0-1) for prioritization</summary>
    public double CategoryWeight { get; set; }
}

/// <summary>
/// Link selection strategy based on SEO best practices
/// </summary>
public sealed class LinkSelectionStrategy
{
    public int ParentLinks { get; set; } = 1;
    public int SiblingLinks { get; set; } = 3;
    public int ChildrenLinks { get; set; } = 2;
    public int AncestorLinks { get; set; } = 2;
    public int CrossPillarLinks { get; set; } = 2;
    public int RotationSeed { get; set; }
}

/// <summary>
/// A set of pages grouped by SEO category
/// </summary>
public sealed class PageSet
{
    public string Category { get; set; } = "";
    public List<SitemapPage> Pages { get; set; } = [];
    public double Weight { get; set; }
    public string Reason { get; set; } = "";
}
